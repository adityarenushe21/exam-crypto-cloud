"""One exception type with a stable reason_code (shared with Nayan/Ansh later)."""


class ExamCryptoError(Exception):
    """Raised for every expected failure. Messages never contain secrets."""

    def __init__(self, reason_code: str, message: str = ""):
        self.reason_code = reason_code
        super().__init__(f"{reason_code}: {message}" if message else reason_code)


